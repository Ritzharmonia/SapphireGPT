/**
 * Handles incoming chat messages array, maintaining dialogue memory
 */
export function generateSapphireResponse(
  messages: Array<{ role: string; content: string }>,
  _systemInstruction?: string
): string {
  if (!messages || messages.length === 0) {
    return 'Сайн байна уу! Би танд юугаар туслах вэ? Чөлөөтэй асуугаарай.';
  }

  const userMessages = messages.filter((m) => m.role === 'user');
  const lastUserMsg = userMessages[userMessages.length - 1];
  const query = (lastUserMsg?.content || '').trim();

  // Multi-turn context handling for incomplete follow-up queries (e.g. "ажилтан нь хэн бэ?", "хэдэн настай вэ?")
  if (userMessages.length > 1 && query.length < 35) {
    const prevMsg = userMessages[userMessages.length - 2]?.content || '';
    const combined = `${prevMsg} ${query}`.toLowerCase();

    // If query has no specific entity on its own, resolve via combined context
    if (/(газрын\s*яам|лидиа)/i.test(combined) && /(ажилтан|ажилчид|хэд)/i.test(query.toLowerCase())) {
      return `Газрын яамны тэргүүн Лидиа Чармиелл нь **ганцаараа ажилладаг**, ямар ч туслах эсвэл өөр ажилтан байхгүй юм.`;
    }
    if (/(боомт)/i.test(combined) && /(менежер|ажилтан|хэн)/i.test(query.toLowerCase()) && !/(виконт|канцлер|зөвлөх)/i.test(query)) {
      return `Боомтын менежерээр **Винтэр Дэ Алгер Обелиа (Winter De Alger Obelia)** ажилладаг.`;
    }
    if (/(сансет|хот)/i.test(combined) && /(дарга|тэргүүн|хоч)/i.test(query.toLowerCase())) {
      return `Сансет Вейл хотын дарга нь **Андрес Агриче**, харин хоч бичээч нь **Каервин Вон Монтакью** юм.`;
    }
  }

  return resolveSapphireQuery(query);
}
